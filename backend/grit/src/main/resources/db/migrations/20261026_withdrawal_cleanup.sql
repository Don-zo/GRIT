-- 자동 migration runner는 사용하지 않는다. 배포 전 PostgreSQL에서 수동 적용할 DDL.
-- 기존 운영 설정 ddl-auto=update도 동일 테이블을 생성할 수 있다.
CREATE TABLE IF NOT EXISTS withdrawal_cleanup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_name UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_withdrawal_cleanup_due
    ON withdrawal_cleanup (next_attempt_at, id);
